def main() -> None:
    app = create_app()
    endpoints: dict[str, list[str]] = {}
    for path, methods in app.openapi()["paths"].items():
        for method, op in methods.items():
            for fid in re.findall(r"\b(\d{1,2}\.\d)\b", op.get("summary", "")):
                endpoints.setdefault(fid, []).append(f"`{method.upper()} {path}`")
    out = sys.stdout
    out.write("# Traceability: function -> plugin -> API -> screen\n\n")
    out.write("Generated by `backend/scripts/traceability.py` from the running plugin registry. ")
    out.write("Function IDs follow the Project Vision product decomposition (Table 13).\n\n")
    out.write("| ID | Function | Phase | Plugin | API endpoints | Mobile screen |\n|---|---|---|---|---|---|\n")
    rows = []
    for plugin in registry.all():
        for fid, title in plugin.functions.items():
            rows.append((fid, title, plugin))
    rows.sort(key=lambda r: tuple(int(x) for x in r[0].split(".")))
    for fid, title, plugin in rows:
        phase = "Growth" if "(Growth)" in title or plugin.phase == "Growth" else plugin.phase
        apis = "<br>".join(sorted(set(endpoints.get(fid, [])))) or "event-driven / see plugin"
        name = title.replace(" (Growth)", "")
        out.write(f"| {fid} | {name} | {phase} | `{plugin.name}` | {apis} | {SCREENS.get(fid, '')} |\n")
    out.write(f"\n{len(rows)} functions traced.\n")


if __name__ == "__main__":
    main()
